describe('findAttribution', () => {
  it.each([
    'fix\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>',
    'fix\n\nco-authored-by: Вася <v@x.ru>',
    'fix\n\nCo-authored-by=someone',
    'fix\n\nCo‑Authored‑By: Claude',
    'fix\n\nCo-Author​ed-By: Claude',
    'fix\n\nCo-Authored-By： Claude',
    '🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    'Generated by Claude',
    'see https://claude.ai/code/session_123',
    'fix\n\nClaude-Session: abc',
    'mail noreply@anthropic.com',
  ])('finds attribution in %j', (text) => {
    expect(findAttribution(text)).not.toBeNull()
  })

  it.each([
    'Добавил ретраи в клиент Claude API',
    'Обновил модель на claude-opus-5-5',
    'Authored by команда',
    'fix: co-author support in UI',
  ])('ignores %j', (text) => {
    expect(findAttribution(text)).toBeNull()
  })
})

const denied = (command, extra = {}) => evaluate({ command, lastUserMessage: 'пушь', ...extra })?.decision === 'deny'

describe('pre-commit layer', () => {
  it.each([
    'git commit -m "fix" -m "Co-Authored-By: Claude <noreply@anthropic.com>"',
    `git commit -m "$(cat <<'EOF'\nfix\n\nCo-Authored-By: Claude <noreply@anthropic.com>\nEOF\n)"`,
    'git commit -F - <<EOF\nfix\n\n🤖 Generated with Claude Code\nEOF',
    'git commit --trailer "Co-authored-by: Claude <noreply@anthropic.com>" -m fix',
    'git commit --amend --trailer co-authored-by=claude -m fix',
    'cd repo && git tag -a v1 -m "Generated with Claude Code"',
    'gh pr create --title x --body "🤖 Generated with [Claude Code](https://claude.com/claude-code)"',
    'glab mr create --description "Co-Authored-By: Claude"',
    'gh api repos/a/b/git/commits -f message="x\n\nCo-Authored-By: Claude"',
  ])('denies %s', (cmd) => {
    expect(denied(cmd)).toBe(true)
  })

  it('reads -F message file', () => {
    const files = { '/repo/msg.txt': 'fix\n\nCo-Authored-By: Claude' }
    expect(denied('cd /repo && git commit -F msg.txt', { readFile: (p) => files[p] ?? null })).toBe(true)
    expect(denied('git commit -F "/repo/msg.txt"', { readFile: (p) => files[p] ?? null })).toBe(true)
  })

  it('reads gh --body-file', () => {
    const files = { '/repo/body.md': 'Generated with Claude Code' }
    expect(denied('gh pr create --body-file=/repo/body.md', { readFile: (p) => files[p] ?? null })).toBe(true)
  })

  it('allows clean commits and audits', () => {
    expect(denied('git commit -m "Добавил ретраи"')).toBe(false)
    expect(denied('grep -rn "Co-Authored-By" .')).toBe(false)
    expect(denied('git log --grep "Co-authored-by"')).toBe(false)
  })
})

describe('push layer', () => {
  it('denies push when unpushed commit has attribution', () => {
    const unpushed = () => [{ sha: 'abcdef1234', message: 'fix\n\nCo-Authored-By: Claude' }]
    expect(denied('git push', { unpushedMessages: unpushed })).toBe(true)
  })

  it('denies push when check fails', () => {
    const unpushed = () => { throw new Error('boom') }
    expect(denied('git push', { unpushedMessages: unpushed })).toBe(true)
  })

  it('passes refspec source to the check', () => {
    let seen
    evaluate({ command: 'git push origin +feature:main', lastUserMessage: 'пушь', unpushedMessages: (dir, src) => { seen = src; return [] } })
    expect(seen).toEqual(['feature'])
  })
})

describe('real git repo', () => {
  let repo
  const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'] })

  beforeAll(() => {
    const root = mkdtempSync(join(tmpdir(), 'guard-git-'))
    const remote = join(root, 'remote.git')
    repo = join(root, 'work')
    execFileSync('git', ['init', '-q', '--bare', remote])
    execFileSync('git', ['init', '-q', '-b', 'main', repo])
    git('config', 'user.email', 't@t')
    git('config', 'user.name', 't')
    git('config', 'commit.gpgsign', 'false')
    git('remote', 'add', 'origin', remote)
    writeFileSync(join(repo, 'a.txt'), '1')
    git('add', '.')
    git('commit', '-q', '-m', 'init')
    git('push', '-q', 'origin', 'main')
    writeFileSync(join(repo, 'a.txt'), '2')
    git('commit', '-q', '-am', 'fix', '-m', 'Co-Authored-By: Claude <noreply@anthropic.com>')
  })

  it('push layer catches attribution in a real unpushed commit', () => {
    const v = evaluate({ command: 'git push origin main', lastUserMessage: 'пушь', cwd: repo, readFile: readMessageFile, unpushedMessages })
    expect(v?.reason).toMatch(/атрибуц/)
  })

  it('post layer reports the fresh commit', () => {
    expect(inspect({ command: 'git commit -am fix', cwd: repo, unpushed: unpushedMessages })).toMatch(/атрибуц/)
  })

  it('post layer catches commits made by a script outside cwd', () => {
    expect(inspect({ command: `sh /somewhere/commit.sh ${repo}`, cwd: tmpdir(), unpushed: unpushedMessages })).toMatch(/атрибуц/)
    expect(inspect({ command: `cd ${repo} && ./do-stuff.sh`, cwd: tmpdir(), unpushed: unpushedMessages })).toMatch(/атрибуц/)
  })

  it('post layer is quiet after the message is fixed', () => {
    git('commit', '-q', '--amend', '-m', 'fix')
    expect(inspect({ command: 'git commit --amend -m fix', cwd: repo, unpushed: unpushedMessages })).toBeNull()
    const v = evaluate({ command: 'git push', lastUserMessage: 'пушь', cwd: repo, readFile: readMessageFile, unpushedMessages })
    expect(v).toBeNull()
  })
})

describe('guard-post failures', () => {
  it('warns when the hook crashes', () => {
    const out = decidePost(JSON.stringify({ tool_name: 'Bash', tool_input: { command: 'git commit -m x' } }), { inspect: () => { throw new Error('boom') } })
    expect(JSON.parse(out).decision).toBe('block')
    expect(JSON.parse(out).reason).toContain('git log -1')
  })

  it('warns when stdin is broken', () => {
    expect(JSON.parse(decidePost('{oops')).decision).toBe('block')
  })

  it('warns when commits cannot be read', () => {
    const reason = inspect({ command: 'git commit -m x', cwd: '/repo', unpushed: () => { throw new Error('lock') }, toplevel: () => '/repo', dirExists: () => false })
    expect(reason).toContain('/repo')
  })

  it('stays quiet for other tools', () => {
    expect(decidePost(JSON.stringify({ tool_name: 'Read' }))).toBe(null)
  })
})
